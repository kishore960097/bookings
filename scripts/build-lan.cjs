#!/usr/bin/env node
/**
 * scripts/build-lan.cjs
 *
 * Debug-only LAN APK build script.
 *
 * Workflow:
 *   1. Detect this PC's current LAN IPv4 address (via scripts/lan-ip.cjs).
 *   2. Rewrite android/app/src/debug/res/xml/network_security_config.xml with current IP.
 *   3. Set VITE_API_URL=http://<LAN_IP>:3000 and CAPACITOR_DEBUG_LAN=true in the process environment.
 *   4. Run: vite build   (bakes the URL into the JS bundle)
 *   5. Run: cap sync android (enables CapacitorHttp natively for debug LAN)
 *   6. Run: gradlew assembleDebug  (produces app-debug.apk)
 *
 * IMPORTANT: This script is for DEBUG builds only.
 * Release builds must use an HTTPS API URL set in the deploy CI environment.
 * Never commit a release APK built with an HTTP LAN URL.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execSync } = require('child_process');

// ── 1. Detect LAN IP ─────────────────────────────────────────────────────────
const ifaces = os.networkInterfaces();
let lanIp = '';
for (const name of Object.keys(ifaces)) {
  for (const entry of (ifaces[name] ?? [])) {
    if (entry.family === 'IPv4' && !entry.internal) {
      lanIp = entry.address;
      break;
    }
  }
  if (lanIp) break;
}

if (!lanIp) {
  process.stderr.write('[QGo] ERROR: No LAN IPv4 found. Connect to WiFi and retry.\n');
  process.exit(1);
}

const apiUrl = `http://${lanIp}:3000`;
console.log(`[QGo] LAN IP detected: ${lanIp}`);
console.log(`[QGo] Building debug APK with VITE_API_URL=${apiUrl}`);
console.log('[QGo] NOTE: This APK is for DEBUG only. Release stays HTTPS.');
console.log('');

// ── 2. Update network_security_config.xml automatically ─────────────────────
const netSecPath = path.join(
  __dirname,
  '..',
  'android',
  'app',
  'src',
  'debug',
  'res',
  'xml',
  'network_security_config.xml'
);

if (fs.existsSync(netSecPath)) {
  const xmlContent = `<?xml version="1.0" encoding="utf-8"?>
<!-- Auto-generated by scripts/build-lan.cjs for debug builds. Do not commit hardcoded LAN IPs. -->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${lanIp}</domain>
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">10.0.2.2</domain>
        <trust-anchors>
            <certificates src="system" />
            <certificates src="user" />
        </trust-anchors>
    </domain-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;
  fs.writeFileSync(netSecPath, xmlContent, 'utf8');
  console.log(`[QGo] Updated network_security_config.xml with debug LAN IP: ${lanIp}`);
}

// ── 3. Inject into environment for debug build ──────────────────────────────
process.env.VITE_API_URL = apiUrl;
process.env.VITE_QGO_DEBUG = 'true';
process.env.CAPACITOR_DEBUG_LAN = 'true';

// ── 4. Helper ────────────────────────────────────────────────────────────────
function run(cmd, cwd) {
  console.log(`\n$ ${cmd}`);
  execSync(cmd, { stdio: 'inherit', cwd: cwd || process.cwd(), shell: true });
}

// ── 5. Build steps ───────────────────────────────────────────────────────────
try {
  run('npx vite build');
  run('npx cap sync android');
  // gradlew is a batch file on Windows; must be called with the shell
  run('gradlew.bat assembleDebug', path.join(process.cwd(), 'android'));
  const srcApk = path.join(process.cwd(), 'android', 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk');
  const destApk = path.join(process.cwd(), 'QGo-v1.0.2-debug.apk');
  if (fs.existsSync(srcApk)) {
    fs.copyFileSync(srcApk, destApk);
    fs.copyFileSync(srcApk, path.join(process.cwd(), 'QGo-latest.apk'));
    fs.copyFileSync(srcApk, path.join(process.cwd(), 'QGo-Public-Cloud.apk'));
    const pubApk = path.join(process.cwd(), 'public', 'qgo-app.apk');
    fs.mkdirSync(path.dirname(pubApk), { recursive: true });
    fs.copyFileSync(srcApk, pubApk);
    console.log(`[QGo] Copied to project root: ${destApk} and QGo-latest.apk and public/qgo-app.apk`);
  }
} catch (err) {
  console.error('[QGo] Build failed:', err.message);
  process.exit(1);
}

console.log('');
console.log('[QGo] ✔ Debug APK built successfully.');
console.log(`[QGo]   Path: QGo-v1.0.2-debug.apk (and android/app/build/outputs/apk/debug/app-debug.apk)`);
console.log(`[QGo]   API:  ${apiUrl}`);
console.log('[QGo]   Install: adb install android/app/build/outputs/apk/debug/app-debug.apk');
console.log('');
console.log('[QGo] Windows Firewall rule (run once as Administrator to allow phone connections):');
console.log('  netsh advfirewall firewall add rule name="QGo Dev Server" dir=in action=allow protocol=TCP localport=3000');
